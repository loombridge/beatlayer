//! The command registry: every action a person or an agent can take in
//! Beatlayer (decisions D16 and D17).
//!
//! The registry is the plug-in kit's `lspk-commands`; this crate re-exports
//! it under the name Beatlayer's crates use, so `bl_commands::Registry`,
//! `bl_commands::CommandSpec` and the rest are `lspk_commands`' items at the
//! same paths. Only [`reference`] adds something: Beatlayer's own opening for
//! the command reference that `cargo xtask commands` generates.
//!
//! The contexts are the UI parity reference's, and default bindings name
//! its shortcuts by ID.

pub use lspk_commands::*;

pub mod readback;

/// The command reference, generated from the registry by
/// `cargo xtask commands`, with Beatlayer's opening.
pub mod reference {
    pub use lspk_commands::reference::*;

    use crate::{Registry, ShortcutTable};

    /// Beatlayer's opening for the command reference.
    pub const INTRO: &str = "# Command reference\n\
     \n\
     <!-- Generated by `cargo xtask commands` from the command registry. Don't edit it by \
     hand: `cargo xtask check` fails if it differs from what the registry generates. -->\n\
     \n\
     Every action a person or an agent can take in Beatlayer is a command in the registry \
     (`crates/commands`). Menus, shortcuts, key and MIDI mapping, the agent API, and tests \
     all run commands by the IDs below, so an action has one implementation however it's \
     reached (decisions D16 and D17 in [the architecture](../02-architecture.md#decisions-log)).\n\
     \n\
     Each command has:\n\
     \n\
     - an **ID** that never changes, which key maps, MIDI maps, agents, and logs use;\n\
     - a **label**: what a person sees in menus and key-mapping lists;\n\
     - a **description** written for a model: what it does, when to use it, and what it \
     changes;\n\
     - a **permission class**, which decides whether an agent asks first;\n\
     - **contexts**: the parts of the interface where a person reaches it, as \
     [the UI parity reference](../ui-parity/README.md) names them;\n\
     - **default keys**: shortcuts from [the UI parity reference](../ui-parity/shortcuts.md), \
     by ID, with any arguments they fix. The UI supplies the other arguments from the \
     selection in the shortcut's context, a text field, or a gesture. A command Live has \
     no shortcut for has no default keys;\n\
     - **arguments** and a **result** as JSON Schemas generated from the Rust types. An \
     agent sends the arguments as a JSON object. The types they use are under \
     [Types](#types);\n\
     - a **readback** for every command that isn't `read`: the read command or query that shows \
     its effect, so an agent can check what it did ([Readback](#readback)).\n";

    /// Renders Beatlayer's command reference as Markdown: [`INTRO`], then
    /// everything [`markdown_with_intro`] generates from the registry.
    ///
    /// # Errors
    ///
    /// As [`markdown_with_intro`].
    pub fn markdown(registry: &Registry, shortcuts: &ShortcutTable) -> Result<String, String> {
        markdown_with_intro(registry, shortcuts, INTRO)
    }
}
